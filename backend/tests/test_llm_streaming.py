def _register_and_get_token(client: TestClient) -> str:
    """Register a test user and return the JWT from the response."""
    resp = client.post(
        "/auth/register",
        json={"email": TEST_EMAIL, "password": TEST_PASSWORD},
    )
    assert resp.status_code == 201, resp.text
    return resp.json()["token"]


def _auth_headers(token: str) -> dict[str, str]:
    return {"Authorization": f"Bearer {token}"}


def _create_conversation(client: TestClient, token: str) -> str:
    """Create a conversation and return its id."""
    resp = client.post("/conversations", headers=_auth_headers(token))
    assert resp.status_code in (200, 201), resp.text
    body = resp.json()
    assert "id" in body, f"conversation response must include 'id'; got: {body}"
    return body["id"]


def _send_message(client: TestClient, token: str, conversation_id: str, content: str = "Hello"):
    """POST a message and return the raw response (SSE stream)."""
    return client.post(
        f"/conversations/{conversation_id}/messages",
        headers=_auth_headers(token),
        json={"content": content},
    )


# --------------------------------------------------------------------------- #
# AC-056: answer generated by configured OpenAI model and streamed back
# --------------------------------------------------------------------------- #


def test_send_message_streams_openai_answer(make_streaming_app) -> None:
    """AC-056: a message produces an SSE stream containing the model's reply.

    The OpenAI client is mocked to "generate" ``FAKE_REPLY``.  The response
    must be an event stream whose body contains that reply, proving the
    handler called the configured model and streamed the result back rather
    than returning a static stub.
    """
    client, mock_client = make_streaming_app(model="gpt-4o-mini")

    token = _register_and_get_token(client)
    conv_id = _create_conversation(client, token)
    response = _send_message(client, token, conv_id, "What is 2+2?")

    assert response.status_code == 200, response.text

    # The response must be streamed as server-sent events.
    content_type = response.headers.get("content-type", "")
    assert (
        "text/event-stream" in content_type
    ), f"streaming endpoint must return text/event-stream; got {content_type!r}"

    # The body must contain the fake reply the mocked model "generated".
    body = response.text
    assert (
        FAKE_REPLY in body
    ), f"streamed body must contain the model's reply {FAKE_REPLY!r}; got: {body[:300]}"

    # The OpenAI client must have been called (the answer came from the model).
    assert (
        mock_client.chat.completions.create.called
    ), "the OpenAI client must be called to generate the answer"


def test_streamed_response_contains_multiple_sse_events(make_streaming_app) -> None:
    """AC-056: the response is genuinely streamed -- multiple SSE data events.

    The fake reply is split across several chunks, so the response body must
    contain more than one ``data:`` event, proving token-by-token streaming
    rather than a single buffered blob.
    """
    client, _mock = make_streaming_app(model="gpt-4o-mini")

    token = _register_and_get_token(client)
    conv_id = _create_conversation(client, token)
    response = _send_message(client, token, conv_id)

    assert response.status_code == 200, response.text
    data_events = [line for line in response.text.splitlines() if line.startswith("data:")]
    assert len(data_events) >= 2, (
        f"streamed response must contain multiple SSE data events; got {len(data_events)} "
        f"in body: {response.text[:300]}"
    )


# --------------------------------------------------------------------------- #
# AC-059: model name is configurable, changed by env var + restart
# --------------------------------------------------------------------------- #


def test_default_model_is_passed_to_openai(make_streaming_app) -> None:
    """AC-059: the default ``OPENAI_MODEL`` is what the OpenAI client receives."""
    client, mock_client = make_streaming_app(model="gpt-4o-mini")

    token = _register_and_get_token(client)
    conv_id = _create_conversation(client, token)
    _send_message(client, token, conv_id)

    assert mock_client.chat.completions.create.called
    call_kwargs = mock_client.chat.completions.create.call_args.kwargs
    assert (
        call_kwargs.get("model") == "gpt-4o-mini"
    ), f"OpenAI client must be called with model='gpt-4o-mini'; got {call_kwargs.get('model')!r}"


def test_custom_model_is_passed_to_openai(make_streaming_app) -> None:
    """AC-059: a non-default ``OPENAI_MODEL`` is forwarded to the OpenAI client."""
    client, mock_client = make_streaming_app(model="gpt-4o")

    token = _register_and_get_token(client)
    conv_id = _create_conversation(client, token)
    _send_message(client, token, conv_id)

    assert mock_client.chat.completions.create.called
    call_kwargs = mock_client.chat.completions.create.call_args.kwargs
    assert (
        call_kwargs.get("model") == "gpt-4o"
    ), f"OpenAI client must be called with model='gpt-4o'; got {call_kwargs.get('model')!r}"


def test_changing_model_with_restart_uses_new_model(make_streaming_app) -> None:
    """AC-059: after changing ``OPENAI_MODEL`` and restarting, the new model is used.

    Two separate app instances are booted with different ``OPENAI_MODEL``
    values (simulating an operator change + restart).  The first must call
    OpenAI with the first model, the second with the second -- no code change.
    """
    # First start: model A.
    client_a, mock_a = make_streaming_app(model="gpt-4o")
    token_a = _register_and_get_token(client_a)
    conv_a = _create_conversation(client_a, token_a)
    _send_message(client_a, token_a, conv_a)
    model_a = mock_a.chat.completions.create.call_args.kwargs.get("model")

    # Second start: model B (same code, different env var).
    client_b, mock_b = make_streaming_app(model="gpt-4o-mini")
    token_b = _register_and_get_token(client_b)
    conv_b = _create_conversation(client_b, token_b)
    _send_message(client_b, token_b, conv_b)
    model_b = mock_b.chat.completions.create.call_args.kwargs.get("model")

    assert model_a == "gpt-4o", f"first start should use gpt-4o; got {model_a!r}"
    assert model_b == "gpt-4o-mini", f"second start should use gpt-4o-mini; got {model_b!r}"
    assert model_a != model_b, "the two starts must use different models"


# --------------------------------------------------------------------------- #
# AC-058 (streaming path): API key never in the streamed response
# --------------------------------------------------------------------------- #


def test_api_key_absent_from_streamed_response(make_streaming_app) -> None:
    """AC-058: the API key must not appear in the SSE-streamed response body.

    The mocked client is constructed with ``FAKE_KEY`` in the environment.
    The streamed response -- the body the browser would receive -- must not
    contain it.
    """
    client, _mock = make_streaming_app(model="gpt-4o-mini")

    token = _register_and_get_token(client)
    conv_id = _create_conversation(client, token)
    response = _send_message(client, token, conv_id)

    assert (
        FAKE_KEY not in response.text
    ), f"API key leaked in streamed response body: {response.text[:300]}"
    # Also check the response headers.
    for header_value in response.headers.values():
        assert FAKE_KEY not in header_value, f"API key leaked in response header: {header_value}"
