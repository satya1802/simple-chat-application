"""End-to-end tests for LLM message streaming (US-017 AC-056, AC-059).

These tests verify the streaming and model-configuration contract:

* AC-056: When ``OPENAI_API_KEY`` and a model name are set, sending a message
  produces an SSE-streamed answer generated by the configured OpenAI model.
* AC-059: The model name is read from ``OPENAI_MODEL``; changing it (with a
  restart) changes the model passed to the OpenAI client -- no code change.

The OpenAI API is never called: ``openai.OpenAI`` and ``openai.AsyncOpenAI``
are patched so no network request leaves the test run.  Every fake streaming
chunk mimics the shape of a real ``chat.completions.create(stream=True)`` delta
so the handler under test exercises the same iteration path it would in
production.
"""

from __future__ import annotations

import importlib
import os
import sys
import types
from collections.abc import Iterator
from unittest.mock import MagicMock, patch

import pytest
from fastapi.testclient import TestClient
from sqlalchemy import create_engine
from sqlalchemy.orm import Session, sessionmaker
from sqlalchemy.pool import StaticPool

# A recognizable fake key so a leak would be unmistakable.
FAKE_KEY = "sk-streaming-canary-0123456789abcdef"
# The fake reply the mocked OpenAI client "generates".
FAKE_REPLY = "Hello from the configured model."
# Credentials for the test user.
TEST_EMAIL = "streamer@example.com"
TEST_PASSWORD = "correct horse battery staple"


# --------------------------------------------------------------------------- #
# Helpers
# --------------------------------------------------------------------------- #


def _purge_app_modules() -> None:
    """Remove every already-imported ``app`` module so config reads re-run."""
    for mod in list(sys.modules):
        if mod == "app" or mod.startswith("app."):
            del sys.modules[mod]


def _fake_stream_chunks(text: str) -> list[types.SimpleNamespace]:
    """Build fake OpenAI streaming chunks whose deltas spell *text* token by token.

    Each chunk mimics ``ChatCompletionChunk``: ``chunk.choices[0].delta.content``
    carries one piece of the reply.  A final chunk carries ``finish_reason``.
    """
    chunks: list[types.SimpleNamespace] = []
    for piece in text.split():
        chunk = types.SimpleNamespace()
        chunk.choices = [
            types.SimpleNamespace(
                delta=types.SimpleNamespace(content=piece + " "),
                finish_reason=None,
            )
        ]
        chunks.append(chunk)
    # Final chunk: no content, finish_reason set.
    final = types.SimpleNamespace()
    final.choices = [
        types.SimpleNamespace(
            delta=types.SimpleNamespace(content=None),
            finish_reason="stop",
        )
    ]
    chunks.append(final)
    return chunks


# --------------------------------------------------------------------------- #
# Factory fixture: build a fresh app with a mocked OpenAI client
# --------------------------------------------------------------------------- #


@pytest.fixture()
def make_streaming_app():
    """Factory that creates a TestClient with a mocked OpenAI client.

    ``make_streaming_app(model=...)`` purges all ``app`` modules, patches the
    OpenAI client classes, re-imports the application, and yields a
    ``(TestClient, mock_client)`` pair.  The model parameter controls the
    ``OPENAI_MODEL`` env var read at import time, so each invocation simulates
    a fresh server start with a potentially different configured model.
    """
    saved_env = os.environ.copy()
    created: list[tuple] = []

    def _make(model: str = "gpt-4o-mini") -> tuple[TestClient, MagicMock]:
        os.environ["OPENAI_API_KEY"] = FAKE_KEY
        os.environ["JWT_SECRET"] = "test-jwt-secret-not-for-production"
        os.environ["DATABASE_URL"] = "sqlite:///./test_streaming.db"
        os.environ["OPENAI_MODEL"] = model
        os.environ.pop("SYSTEM_PROMPT", None)

        _purge_app_modules()

        with patch("openai.OpenAI") as mock_cls, patch("openai.AsyncOpenAI") as mock_async_cls:
            mock_client = MagicMock()
            mock_cls.return_value = mock_client
            mock_async_cls.return_value = mock_client
            # Each call to create returns a *fresh* iterator of fake chunks.
            mock_client.chat.completions.create.side_effect = lambda **kw: iter(
                _fake_stream_chunks(FAKE_REPLY)
            )

            # Import models first so tables register on Base.
            importlib.import_module("app.models")
            database = importlib.import_module("app.database")
            Base = database.Base

            engine = create_engine(
                "sqlite://",
                connect_args={"check_same_thread": False},
                poolclass=StaticPool,
                future=True,
            )
            Base.metadata.create_all(bind=engine)
            TestSession = sessionmaker(bind=engine, autoflush=False, expire_on_commit=False)

            main = importlib.import_module("app.main")
            app = main.app

            def _override_get_db() -> Iterator[Session]:
                session = TestSession()
                try:
                    yield session
                finally:
                    session.close()

            app.dependency_overrides[database.get_db] = _override_get_db

            tc = TestClient(app)
            tc.__enter__()
            created.append((tc, mock_client, engine, app, database))
            return tc, mock_client

    yield _make

    for tc, _mock, engine, app, database in created:
        tc.__exit__(None, None, None)
        app.dependency_overrides.clear()
        database.Base.metadata.drop_all(bind=engine)
        engine.dispose()

    _purge_app_modules()
    os.environ.clear()
    os.environ.update(saved_env)


